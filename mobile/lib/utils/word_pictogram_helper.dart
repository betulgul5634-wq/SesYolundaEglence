  static String getPictogram(String word) {
    if (word.isEmpty) return '✨';
    final clean = word.trim().toLowerCase().replaceAll('\u0307', '');

    // 1. Doğrudan tam eşleşme
    if (_dict.containsKey(clean)) {
      return _dict[clean]!;
    }

    // 2. Kelime/öbek içi token bazlı eşleşme (kısa 3 harfli tesadüfi alt dizgeleri engeller)
    final tokens = clean
        .split(RegExp(r'[^a-zçğıöşü]+'))
        .where((t) => t.isNotEmpty)
        .toList();

    for (final t in tokens) {
      if (_dict.containsKey(t)) {
        return _dict[t]!;
      }
    }

    // 3. Kök / Ek bazlı en uzun eşleşme (Örn: "pazarı" -> "pazar", "patatesleri" -> "patates")
    String? bestEmoji;
    int bestLen = 0;
    for (final t in tokens) {
      for (final entry in _dict.entries) {
        if (entry.key.length > bestLen &&
            t.startsWith(entry.key) &&
            t.length <= entry.key.length + 6) {
          bestLen = entry.key.length;
          bestEmoji = entry.value;
        }
      }
    }
    if (bestEmoji != null) return bestEmoji;

    // 4. Uzun anahtar kelime içerme bazlı en uzun eşleşme (en az 5 harf)
    for (final entry in _dict.entries) {
      if (entry.key.length >= 5 &&
          entry.key.length > bestLen &&
          clean.contains(entry.key)) {
        bestLen = entry.key.length;
        bestEmoji = entry.value;
      }
    }
    if (bestEmoji != null) return bestEmoji;

    // 4. İlk harfe göre sevimli tematik simge
    if (clean.startsWith('p')) return '🎈';
    if (clean.startsWith('b')) return '🫐';
    if (clean.startsWith('t')) return '🎾';
    if (clean.startsWith('d')) return '🐬';
    if (clean.startsWith('k')) return '👑';
    if (clean.startsWith('g')) return '🌈';
