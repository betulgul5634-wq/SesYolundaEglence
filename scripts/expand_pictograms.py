# Find existing dict items to avoid duplicate keys
existing_keys = set(re.findall(r"'([a-zçğıöşü]+)':", text))
print(f"Existing keys in dict: {len(existing_keys)}")

items_to_add = []
for k, v in new_pictograms.items():
    clean_k = k.lower().strip()
    if clean_k not in existing_keys:
        items_to_add.append(f"    '{clean_k}': '{v}',")
        existing_keys.add(clean_k)

print(f"Adding {len(items_to_add)} new pictograms to dictionary")

if items_to_add:
    insert_point = text.find("  static String getPictogram(String word) {")
    # Insert right before getPictogram
    last_brace = text.rfind("};", 0, insert_point)
    text = text[:last_brace] + "    // ── GENİŞLETİLMİŞ GÜNLÜK PİKTOGRAMLAR (TÜM SESLER) ──\n" + "\n".join(items_to_add) + "\n  };\n" + text[insert_point:]

with open(file_path, 'w', encoding='utf-8') as f:
    f.write(text)

print(f"SUCCESS: Total keys now in dict: {len(existing_keys)}")
